def draw_map(cv, x, y, w, h, ocean, land, markers=(), marker_r=9):
    """Draw the world map into rect (x, y, w, h). markers = list of
    (lon, lat, number, color). Returns nothing."""
    cv.fill_rect(x, y, w, h, ocean)
    cw, ch = w / 120.0, h / 60.0
    for my, spans in MAP_SPANS.items():
        for (x0, x1) in spans:
            cv.fill_rect(int(x + x0 * cw), int(y + my * ch),
                         int((x1 - x0 + 1) * cw + 0.5), int(ch + 0.5), land)
    for (lon, lat, num, color) in markers:
        mx = int(x + (lon + 180) / 360.0 * w)
        my = int(y + (90 - lat) / 150.0 * h)
        cv.circle(mx, my, marker_r, color, fill=True)
        cv.circle(mx, my, marker_r, bytes((26, 26, 26)))
        draw_text(cv, mx, my - 5, str(num), 1, bytes((255, 255, 255)), 'c')
