def glyph(ch):
    return FONT.get(ch, FONT.get('?', FONT[' ']))

# ---------------------------------------------------------------- canvas
class Canvas:
    def __init__(self, w, h, bg):
        self.w, self.h = w, h
        self.px = bytearray(bg) * (w * h)
    def set(self, x, y, c):
        if 0 <= x < self.w and 0 <= y < self.h:
            i = (y * self.w + x) * 3
            self.px[i:i+3] = c
    def fill_rect(self, x, y, w, h, c):
        x0, y0 = max(0, x), max(0, y)
        x1, y1 = min(self.w, x + w), min(self.h, y + h)
        for yy in range(y0, y1):
            i = (yy * self.w + x0) * 3
            j = (yy * self.w + x1) * 3
            self.px[i:j] = bytes(c) * (x1 - x0)
    def rect(self, x, y, w, h, c, t=1):
        self.fill_rect(x, y, w, t, c); self.fill_rect(x, y + h - t, w, t, c)
        self.fill_rect(x, y, t, h, c); self.fill_rect(x + w - t, y, t, h, c)
    def hline(self, x, y, w, c, t=1):
        self.fill_rect(x, y, w, t, c)
    def vline(self, x, y, h, c, t=1):
        self.fill_rect(x, y, t, h, c)
    def line(self, x0, y0, x1, y1, c, t=1):
        dx, dy = abs(x1 - x0), abs(y1 - y0)
        sx = 1 if x0 < x1 else -1
        sy = 1 if y0 < y1 else -1
        err = dx - dy
        while True:
            if t == 1:
                self.set(x0, y0, c)
            else:
                self.fill_rect(x0 - t // 2, y0 - t // 2, t, t, c)
            if x0 == x1 and y0 == y1:
                break
            e2 = 2 * err
            if e2 > -dy:
                err -= dy; x0 += sx
            if e2 < dx:
                err += dx; y0 += sy
    def circle(self, cx, cy, r, c, fill=False):
        if fill:
            for yy in range(-r, r + 1):
                half = int((r * r - yy * yy) ** 0.5)
                self.fill_rect(cx - half, cy + yy, half * 2 + 1, 1, c)
            return
        x, y, d = 0, r, 3 - 2 * r
        while x <= y:
            for px, py in ((cx+x, cy+y), (cx-x, cy+y), (cx+x, cy-y), (cx-x, cy-y),
                           (cx+y, cy+x), (cx-y, cy+x), (cx+y, cy-x), (cx-y, cy-x)):
                self.set(px, py, c)
            if d < 0:
                d += 4 * x + 6
            else:
                d += 4 * (x - y) + 10; y -= 1
            x += 1
    def poly_fill(self, pts, c):
        if len(pts) < 3:
            return
        ys = [p[1] for p in pts]
        for y in range(max(0, min(ys)), min(self.h - 1, max(ys)) + 1):
            xs = []
            n = len(pts)
            for i in range(n):
                x0, y0 = pts[i]; x1, y1 = pts[(i + 1) % n]
                if (y0 <= y < y1) or (y1 <= y < y0):
                    xs.append(int(x0 + (y - y0) * (x1 - x0) / (y1 - y0)))
            xs.sort()
            for i in range(0, len(xs) - 1, 2):
                self.fill_rect(xs[i], y, max(1, xs[i+1] - xs[i]), 1, c)
    def poly_line(self, pts, c, t=1, closed=True):
        n = len(pts)
        rng = range(n) if closed else range(n - 1)
        for i in rng:
            x0, y0 = pts[i]; x1, y1 = pts[(i + 1) % n]
            self.line(x0, y0, x1, y1, c, t)

# ---------------------------------------------------------------- text
def text_w(s, scale):
    return len(s) * (5 * scale + scale) - scale

def text_h(scale):
    return 8 * scale

def draw_text(cv, x, y, s, scale, color, align='l'):
    """Draw text; y is the TOP of the 8-row cell. Returns width drawn."""
    if align == 'c':
        x -= text_w(s, scale) // 2
    elif align == 'r':
        x -= text_w(s, scale)
    cx = x
    for ch in s:
        g = glyph(ch)
        for r in range(8):
            row = g[r]
            for col in range(5):
                if row[col] == '#':
                    cv.fill_rect(cx + col * scale, y + r * scale, scale, scale, color)
        cx += 6 * scale
    return text_w(s, scale)

def wrap_text(s, max_w, scale):
    """Greedy word wrap. Returns list of lines (strings)."""
    cw = 6 * scale
    words = s.split(' ')
    lines, cur = [], ''
    for w in words:
        t = w if not cur else cur + ' ' + w
        if len(t) * cw - scale <= max_w or not cur:
            cur = t
        else:
            lines.append(cur); cur = w
    if cur:
        lines.append(cur)
    return lines

def draw_block(cv, x, y, lines, scale, color, leading=None, align='l'):
    lh = leading if leading is not None else 10 * scale
    for ln in lines:
        draw_text(cv, x, y, ln, scale, color, align)
        y += lh
    return y

# ---------------------------------------------------------------- PNG encoder (stdlib only, deterministic)
def _chunk(typ, data):
    out = struct.pack('>I', len(data)) + typ + data
    out += struct.pack('>I', zlib.crc32(typ + data) & 0xffffffff)
    return out

def encode_png(cv):
    w, h = cv.w, cv.h
    ihdr = struct.pack('>IIBBBBB', w, h, 8, 2, 0, 0, 0)
    raw = bytearray()
    for y in range(h):
        raw.append(0)
        raw += cv.px[y * w * 3:(y + 1) * w * 3]
    comp = zlib.compress(bytes(raw), 9)
    return (b'\x89PNG\r\n\x1a\n' + _chunk(b'IHDR', ihdr)
            + _chunk(b'IDAT', comp) + _chunk(b'IEND', b''))

def save_png(cv, path):
    data = encode_png(cv)
    with open(path, 'wb') as f:
        f.write(data)
    return len(data)

